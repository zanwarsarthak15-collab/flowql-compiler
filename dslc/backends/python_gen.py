"""
FlowQL to Python / pandas Code Generator.

Generates clean, idiomatic pandas scripts from FlowQL IR steps.
Each block contains a clear comment mapping back to the original FlowQL stage.
"""
from typing import List, Set, Dict, Any
from dslc.ir import IRStep, expr_to_str
from dslc.ast_nodes import (
    Expr,
    NumberLiteral,
    StringLiteral,
    BoolLiteral,
    Identifier,
    BinaryOp,
    UnaryOp,
)


def expr_to_pandas(expr: Expr, df_name: str, known_vars: Set[str]) -> str:
    """
    Converts a FlowQL expression AST into pandas boolean indexing or calculation syntax.
    Distinguishes dataframe columns from external scalar variables.
    """
    if isinstance(expr, NumberLiteral):
        return str(expr.value)
    elif isinstance(expr, StringLiteral):
        return repr(expr.value)
    elif isinstance(expr, BoolLiteral):
        return "True" if expr.value else "False"
    elif isinstance(expr, Identifier):
        if expr.name in known_vars:
            return expr.name
        # Assume it's a dataframe column
        return f'{df_name}["{expr.name}"]'
    elif isinstance(expr, UnaryOp):
        sub = expr_to_pandas(expr.expr, df_name, known_vars)
        if expr.op == "not":
            return f"(~{sub})"
        return f"(-{sub})"
    elif isinstance(expr, BinaryOp):
        left = expr_to_pandas(expr.left, df_name, known_vars)
        right = expr_to_pandas(expr.right, df_name, known_vars)
        op = expr.op
        if op == "and":
            return f"({left} & {right})"
        elif op == "or":
            return f"({left} | {right})"
        elif op in ("==", "!=", "<", "<=", ">", ">="):
            return f"({left} {op} {right})"
        else:
            return f"({left} {op} {right})"
    return ""


def expr_to_py_scalar(expr: Expr) -> str:
    """Converts a scalar expression (in let statements) to standard Python syntax."""
    if isinstance(expr, NumberLiteral):
        return str(expr.value)
    elif isinstance(expr, StringLiteral):
        return repr(expr.value)
    elif isinstance(expr, BoolLiteral):
        return "True" if expr.value else "False"
    elif isinstance(expr, Identifier):
        return expr.name
    elif isinstance(expr, UnaryOp):
        sub = expr_to_py_scalar(expr.expr)
        if expr.op == "not":
            return f"not {sub}"
        return f"-{sub}"
    elif isinstance(expr, BinaryOp):
        left = expr_to_py_scalar(expr.left)
        right = expr_to_py_scalar(expr.right)
        return f"({left} {expr.op} {right})"
    return ""


class PythonGenerator:
    """Generates runnable Python/pandas scripts from FlowQL IR steps."""

    def generate(self, steps: List[IRStep]) -> str:
        lines: List[str] = [
            "# =====================================================================",
            "# Generated by FlowQL Compiler (Python/pandas Target)",
            "# =====================================================================",
            "import pandas as pd",
            ""
        ]

        known_vars: Set[str] = set()

        for step in steps:
            lines.append(f"# [FlowQL: Step {step.step_id}] {step.comment}")

            if step.op == "load":
                path = step.details.get("path", "")
                lines.append(f'{step.output_ref} = pd.read_csv("{path}")')

            elif step.op == "let":
                known_vars.add(step.output_ref)
                expr_obj = step.details.get("expr")
                val_str = expr_to_py_scalar(expr_obj) if isinstance(expr_obj, Expr) else step.details.get("expr_str", "None")
                lines.append(f"{step.output_ref} = {val_str}")

            elif step.op == "alias":
                lines.append(f"{step.output_ref} = {step.input_ref}.copy()")

            elif step.op == "filter":
                pred_obj = step.details.get("predicate")
                if isinstance(pred_obj, Expr):
                    pred_code = expr_to_pandas(pred_obj, step.input_ref, known_vars)
                else:
                    pred_code = step.details.get("predicate_str", "True")
                lines.append(f"{step.output_ref} = {step.input_ref}[{pred_code}].reset_index(drop=True)")

            elif step.op == "select":
                cols = step.details.get("columns", [])
                cols_repr = repr(cols)
                lines.append(f"{step.output_ref} = {step.input_ref}[{cols_repr}]")

            elif step.op == "group":
                key_col = step.details.get("key_col", "")
                agg_func = step.details.get("agg_func", "sum").lower()
                agg_col = step.details.get("agg_col", "")
                res_col = step.details.get("result_col", f"{agg_func}_{agg_col}")

                # Pandas aggregation function names
                pd_func = "mean" if agg_func == "avg" else agg_func

                lines.append(
                    f"{step.output_ref} = (\n"
                    f'    {step.input_ref}.groupby("{key_col}", as_index=False)\n'
                    f'    .agg({res_col}=("{agg_col}", "{pd_func}"))\n'
                    f")"
                )

            elif step.op == "sort":
                col = step.details.get("column", "")
                direction = step.details.get("direction", "asc").lower()
                ascending = "True" if direction == "asc" else "False"
                lines.append(
                    f'{step.output_ref} = {step.input_ref}.sort_values(by="{col}", ascending={ascending}).reset_index(drop=True)'
                )

            elif step.op == "limit":
                count = step.details.get("count", 10)
                lines.append(f"{step.output_ref} = {step.input_ref}.head({count})")

            elif step.op == "print":
                table = step.details.get("table", step.input_ref)
                lines.append(f"print({table})")

            lines.append("")

        return "\n".join(lines)
